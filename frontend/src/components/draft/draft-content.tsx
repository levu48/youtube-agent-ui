import { Flag } from "lucide-react";

import { sectionAnchor } from "@/components/draft/draft-outline";
import type { Script } from "@/lib/api";
import { formatClock } from "@/lib/format";
import { humanize } from "@/lib/status";

const FLAG_LABEL: Record<string, string> = {
  source_needed: "Source needed",
  interpretation: "Interpretation",
  quotation_needs_verification: "Quotation: verify",
};

export function DraftContent({ script }: { script: Script }) {
  return (
    <article aria-labelledby="script-title" lang={script.language ?? undefined} className="space-y-8">
      <header className="space-y-2">
        <p className="text-xs font-semibold tracking-wide text-muted-foreground uppercase">Script</p>
        <h2 id="script-title" className="text-2xl leading-snug font-semibold">
          {script.title}
        </h2>
        <p className="text-sm text-muted-foreground">
          {script.target_duration_seconds ? `Target ${formatClock(script.target_duration_seconds)}` : null}
          {script.generated_by ? ` · generated by ${script.generated_by}` : null}
        </p>
      </header>
      {script.sections.map((s, i) => (
        <section
          key={`${s.outline_section_id}-${i}`}
          id={sectionAnchor(s.outline_section_id)}
          aria-labelledby={`${sectionAnchor(s.outline_section_id)}-h`}
          className="scroll-mt-20 space-y-3"
        >
          <div className="space-y-1">
            <h3 id={`${sectionAnchor(s.outline_section_id)}-h`} className="text-xl font-semibold">
              {i + 1}. {s.heading}
            </h3>
            <p className="text-xs text-muted-foreground" lang="en">
              {s.estimated_duration_seconds != null ? `estimated ${formatClock(s.estimated_duration_seconds)}` : ""}
              {s.target_duration_seconds != null ? ` / target ${formatClock(s.target_duration_seconds)}` : ""}
            </p>
          </div>
          <div className="space-y-3 text-base leading-7">
            {s.narration
              .split(/\n{2,}/)
              .filter((p) => p.trim())
              .map((p, j) => (
                <p key={j} className="whitespace-pre-line">
                  {p}
                </p>
              ))}
          </div>
          {s.review_flags.length ? (
            <div className="rounded-lg border border-amber-200 bg-amber-50/70 p-3" lang="en">
              <p className="mb-2 flex items-center gap-1.5 text-sm font-semibold text-warning">
                <Flag aria-hidden className="size-4" /> Review flags ({s.review_flags.length})
              </p>
              <ul className="space-y-2 text-sm">
                {s.review_flags.map((f, j) => (
                  <li key={j}>
                    <span className="mr-1.5 inline-block rounded border border-amber-300 bg-white px-1.5 py-0.5 text-xs font-medium text-warning">
                      {FLAG_LABEL[f.kind] ?? humanize(f.kind)}
                    </span>
                    {f.excerpt ? (
                      <q lang={script.language ?? undefined} className="text-slate-800">
                        {f.excerpt.replace(/^["“”']+|["“”']+$/g, "")}
                      </q>
                    ) : null}
                    {f.note ? <span className="block text-slate-700">{f.note}</span> : null}
                  </li>
                ))}
              </ul>
            </div>
          ) : null}
        </section>
      ))}
    </article>
  );
}
