"use client";

import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { FlaskConical } from "lucide-react";
import { useState } from "react";
import { toast } from "sonner";

import { ConfirmDialog } from "@/components/confirm-dialog";
import { EditError } from "@/components/research/edit-error";
import { LineField, MIN, REVIEWER_HINT, TextField } from "@/components/research/fields";
import { Button } from "@/components/ui/button";
import { ApiError, api, type LineageSegment, type NarrationView } from "@/lib/api";
import { qk } from "@/lib/queries";

const ORIGIN: Record<string, string> = {
  fixture: "Fixture text",
  fixture_derived: "Rewrite, not attested yet",
  human: "Attested rewrite",
  llm: "Model-generated",
};

const REASONS: Record<string, string> = {
  unchanged_fixture_text: "It is still the fixture text: rewrite it first.",
  still_close: "Still close to the fixture text it replaces: rewrite it more thoroughly.",
  not_fixture_derived: "This sentence needs no attestation.",
  unknown_segment: "This sentence changed since the page loaded: reload.",
};

/** Narration lineage (engine D-120): which sentences are still fixture text or unattested
 * rewrites of it. Only a rewrite plus a reviewer's attestation clears the fixture restriction;
 * the engine refuses unchanged or close text and is the only judge. */
export function FixturePanel({ projectId, lang, unsaved }: { projectId: string; lang?: string; unsaved: boolean }) {
  const qc = useQueryClient();
  const q = useQuery({ queryKey: qk.narration(projectId), queryFn: () => api.narration(projectId), staleTime: 0, refetchOnMount: "always" });
  const [picked, setPicked] = useState<string[]>([]);
  const [f, setF] = useState({ reviewer: "", statement: "" });
  const [initOpen, setInitOpen] = useState(false);
  const onDone = (r: { narration: NarrationView }) => {
    qc.setQueryData(qk.narration(projectId), r.narration);
    void qc.invalidateQueries({ queryKey: qk.research(projectId) });
  };
  const attest = useMutation({
    mutationFn: () =>
      api.narrationAttest(projectId, { expected_revision: q.data!.revision!, reviewer: f.reviewer.trim(), statement: f.statement, segment_ids: picked }),
    onSuccess: (r) => {
      onDone(r);
      setPicked([]);
      toast.success(`${r.result.segments.length} sentence(s) attested; ${r.result.remaining} still fixture or unattested`);
    },
  });
  const init = useMutation({
    mutationFn: () => api.provenanceInit(projectId, q.data!.revision!),
    onSuccess: (r) => {
      onDone(r);
      setInitOpen(false);
      toast.success(r.result.recovered === false ? "Lineage initialised: every sentence counts as fixture text" : "Lineage initialised");
    },
  });
  const v = q.data;
  const lineage = v?.lineage;
  if (q.isLoading) return null;
  if (q.isError) return <p className="text-sm text-danger">{(q.error as Error).message}</p>;
  if (!v) return null;
  const segs = lineage?.segments ?? [];
  const left = segs.filter((s) => s.origin === "fixture" || s.origin === "fixture_derived");
  if (!v.needs_init && !lineage?.fixture_project && !v.items.length) return null;
  const byScene = new Map<string, LineageSegment[]>();
  for (const s of left) byScene.set(s.scene_id ?? s.section_id, [...(byScene.get(s.scene_id ?? s.section_id) ?? []), s]);
  const reason = attest.error instanceof ApiError ? (attest.error.details?.reason as string | undefined) : undefined;
  return (
    <section aria-labelledby="fixture-h" className="space-y-3 rounded-lg border p-4 text-sm">
      <h3 id="fixture-h" className="flex items-center gap-1.5 font-semibold">
        <FlaskConical aria-hidden className="size-4" /> Fixture text
      </h3>
      <p className="text-muted-foreground">
        This draft was generated by the offline fixture provider. Research cannot be approved while any sentence is fixture text or a rewrite
        nobody has attested. Rewrite sentences in the Script tab, then attest your rewrites here.
      </p>
      {v.items.map((i, n) => (
        <p key={n} className="rounded border border-amber-300 bg-amber-50 px-2 py-1 text-warning">
          <code className="text-xs">{i.code}</code> {i.detail}
        </p>
      ))}
      {v.needs_init ? (
        <div className="space-y-2">
          <p>This project was drafted before the engine recorded narration lineage. Initialise it first; nothing is marked as human-written.</p>
          <Button size="sm" onClick={() => setInitOpen(true)} disabled={!v.revision || init.isPending}>
            Initialise narration provenance…
          </Button>
          <ConfirmDialog
            open={initOpen}
            onOpenChange={setInitOpen}
            title="Initialise narration provenance?"
            description="The engine recovers the original fixture text offline, from its cache or by regenerating it, and records which sentences changed. If the originals cannot be verified, every current sentence counts as fixture text until rewritten and attested."
            confirmLabel="Initialise"
            cancelLabel="Not now"
            pending={init.isPending}
            onConfirm={() => init.mutate()}
          >
            <EditError error={initOpen ? init.error : null} onReload={() => q.refetch()} />
          </ConfirmDialog>
        </div>
      ) : null}
      {segs.some((s) => s.initialized_from === "legacy_unrecoverable") ? (
        <p className="text-warning">The original fixture text could not be recovered: every sentence counts as fixture text until you rewrite it.</p>
      ) : null}
      {left.length ? (
        <div className="space-y-3">
          {[...byScene.entries()].map(([scene, list]) => (
            <div key={scene}>
              <p className="text-xs font-semibold text-muted-foreground">{scene}</p>
              <ul className="mt-1 space-y-1">
                {list.map((s) => (
                  <li key={s.segment_id} className="flex items-start gap-2 rounded border p-2">
                    {s.origin === "fixture_derived" ? (
                      <input
                        type="checkbox"
                        aria-label={`Attest the rewrite ${s.segment_id}`}
                        checked={picked.includes(s.segment_id)}
                        onChange={(e) => setPicked(e.target.checked ? [...picked, s.segment_id] : picked.filter((x) => x !== s.segment_id))}
                        className="mt-1"
                      />
                    ) : (
                      <span className="w-[13px]" aria-hidden />
                    )}
                    <span className="min-w-0 flex-1">
                      <span lang={lang}>{s.text ?? <span className="italic text-muted-foreground">(normalised) {s.norm}</span>}</span>
                      <span className="block text-xs text-muted-foreground">
                        {ORIGIN[s.origin] ?? s.origin} · {s.segment_id}
                        {s.derived_from.length ? ` · rewrites ${s.derived_from.length} earlier sentence(s)` : ""}
                      </span>
                    </span>
                  </li>
                ))}
              </ul>
            </div>
          ))}
          <form
            className="space-y-2 rounded-md border p-3"
            onSubmit={(e) => {
              e.preventDefault();
              attest.mutate();
            }}
          >
            <p className="font-medium">Attest rewrites ({picked.length} selected)</p>
            <p className="text-xs text-muted-foreground">
              Fixture sentences cannot be attested: rewrite them first. The engine refuses rewrites that still share half or more of their words
              with the fixture text.
            </p>
            <LineField label="Reviewer" value={f.reviewer} onChange={(x) => setF({ ...f, reviewer: x })} required hint={REVIEWER_HINT} />
            <TextField label="What you rewrote, in your words" value={f.statement} onChange={(x) => setF({ ...f, statement: x })} required
              min={MIN.statement} rows={2} />
            {reason && REASONS[reason] ? <p className="text-sm text-danger">{REASONS[reason]}</p> : null}
            <EditError error={attest.error} onReload={() => q.refetch()} />
            <Button type="submit" size="sm" disabled={!picked.length || !f.reviewer.trim() || !f.statement.trim() || attest.isPending || unsaved || !v.revision}>
              {attest.isPending ? "Attesting…" : "Attest rewrite"}
            </Button>
            {unsaved ? <p className="text-xs text-muted-foreground">Save or discard your draft edits first.</p> : null}
          </form>
        </div>
      ) : lineage?.present ? (
        <p className="text-success">Every sentence is a rewrite with an attestation: no fixture text remains.</p>
      ) : null}
    </section>
  );
}
