"use client";

import { useQuery } from "@tanstack/react-query";
import { ArrowLeft, Copy, Eye, FileX, RefreshCw } from "lucide-react";
import Link from "next/link";
import { useParams } from "next/navigation";
import { useState } from "react";
import { toast } from "sonner";

import { DraftContent } from "@/components/draft/draft-content";
import { DraftOutline } from "@/components/draft/draft-outline";
import { DraftValidationPanel } from "@/components/draft/draft-validation-panel";
import { SafeMarkdown } from "@/components/draft/safe-markdown";
import { PageHeader } from "@/components/page-header";
import { EmptyState, ErrorState, LoadingSkeleton } from "@/components/states";
import { Button } from "@/components/ui/button";
import { ApiError, api, type DraftView as Draft, type Script } from "@/lib/api";
import { qk } from "@/lib/queries";

function scriptText(s: Script): string {
  return [s.title, ...s.sections.map((x) => `${x.heading}\n\n${x.narration}`)].join("\n\n");
}

export function DraftView() {
  const { projectId } = useParams<{ projectId: string }>();
  const project = useQuery({ queryKey: qk.project(projectId), queryFn: () => api.project(projectId) });
  const draft = useQuery({ queryKey: qk.draft(projectId), queryFn: () => api.draft(projectId) });
  const [mode, setMode] = useState<"formatted" | "markdown">("formatted");

  const title = project.data?.display_name ?? projectId;
  const projectHref = `/projects/${encodeURIComponent(projectId)}`;
  const d = draft.data;

  const copy = async () => {
    if (!d?.script.data) return;
    try {
      await navigator.clipboard.writeText(scriptText(d.script.data));
      toast.success("Script text copied");
    } catch {
      toast.error("Could not copy");
    }
  };

  return (
    <>
      <PageHeader
        title="Draft"
        badge={
          <span className="inline-flex items-center gap-1 rounded-full border border-slate-300 bg-surface-muted px-2.5 py-0.5 text-xs font-medium text-slate-700">
            <Eye aria-hidden className="size-3.5" /> Read-only
          </span>
        }
        subtitle="Unverified editorial draft generated by the engine. Review it; nothing here is approved research."
        breadcrumbs={[
          { label: "Projects", href: "/projects" },
          { label: title, href: projectHref },
          { label: "Draft" },
        ]}
        actions={
          <>
            <Button asChild variant="outline">
              <Link href={projectHref}>
                <ArrowLeft aria-hidden /> Back to Project
              </Link>
            </Button>
            <Button variant="outline" onClick={() => draft.refetch()} disabled={draft.isFetching}>
              <RefreshCw aria-hidden className={draft.isFetching ? "motion-safe:animate-spin" : undefined} />
              {draft.isFetching ? "Refreshing…" : "Refresh"}
            </Button>
            <Button variant="outline" onClick={copy} disabled={!d?.script.data}>
              <Copy aria-hidden /> Copy text
            </Button>
          </>
        }
      />
      {draft.isLoading ? (
        <LoadingSkeleton rows={3} label="Loading draft" />
      ) : draft.isError ? (
        draft.error instanceof ApiError && draft.error.status === 404 ? (
          <EmptyState title="Project not found" action={<Button asChild><Link href="/">Back to Dashboard</Link></Button>} />
        ) : (
          <ErrorState title="The draft could not be loaded" message={(draft.error as Error).message} onRetry={() => draft.refetch()} />
        )
      ) : d ? (
        <DraftBody draft={d} mode={mode} setMode={setMode} projectHref={projectHref} />
      ) : null}
    </>
  );
}

function DraftBody({
  draft: d,
  mode,
  setMode,
  projectHref,
}: {
  draft: Draft;
  mode: "formatted" | "markdown";
  setMode: (m: "formatted" | "markdown") => void;
  projectHref: string;
}) {
  const nothing = d.outline.state === "missing" && d.script.state === "missing";
  if (nothing) {
    return (
      <EmptyState
        icon={FileX}
        title="No draft yet"
        description="The outline and script have not been generated. Start a draft from the project workspace."
        action={
          <Button asChild>
            <Link href={projectHref}>Back to Project</Link>
          </Button>
        }
      />
    );
  }
  const problems = [d.outline, d.script].filter((a) => a.state !== "ok").map((a) => a.error);
  const script = d.script.data;
  const outline = d.outline.data;
  const showMarkdown = mode === "markdown" || !script;

  return (
    <div className="space-y-6">
      {problems.length ? (
        <ErrorState
          title="Part of the draft is missing or unreadable"
          message={
            <ul className="list-disc pl-5">
              {problems.map((p, i) => (
                <li key={i}>{p}</li>
              ))}
            </ul>
          }
        />
      ) : null}
      {script?.notice ? (
        <p role="note" className="rounded-lg border border-amber-200 bg-amber-50 p-3 text-sm text-warning">
          <strong>Unverified editorial draft.</strong> {script.notice}
        </p>
      ) : null}

      <div className="grid gap-6 lg:grid-cols-[minmax(0,28fr)_minmax(0,72fr)]">
        <aside className="min-w-0 lg:sticky lg:top-20 lg:max-h-[calc(100vh-6rem)] lg:self-start lg:overflow-auto">
          {outline ? (
            <DraftOutline outline={outline} />
          ) : d.outline.markdown ? (
            <SafeMarkdown>{d.outline.markdown}</SafeMarkdown>
          ) : (
            <p className="text-sm text-muted-foreground">Outline unavailable.</p>
          )}
        </aside>
        <div className="min-w-0 space-y-6">
          <div role="group" aria-label="Script view" className="inline-flex rounded-lg border bg-surface p-0.5">
            {(["formatted", "markdown"] as const).map((m) => (
              <button
                key={m}
                type="button"
                aria-pressed={mode === m}
                disabled={m === "formatted" && !script}
                onClick={() => setMode(m)}
                className="rounded-md px-3 py-1.5 text-sm font-medium aria-pressed:bg-primary aria-pressed:text-white disabled:opacity-50"
              >
                {m === "formatted" ? "Formatted" : "Markdown view"}
              </button>
            ))}
          </div>
          <div className="rounded-[var(--radius-panel)] border bg-surface p-5 md:p-8">
            {showMarkdown ? (
              d.script.markdown ? (
                <SafeMarkdown lang={script?.language}>{d.script.markdown}</SafeMarkdown>
              ) : (
                <p className="text-sm text-muted-foreground">script.md is not available.</p>
              )
            ) : (
              <DraftContent script={script!} />
            )}
          </div>
          <DraftValidationPanel check={d.draft_check} error={d.draft_check_error} />
        </div>
      </div>
    </div>
  );
}
